import type { Metadata } from 'next'
import Link from 'next/link'
import { Table, TableWrap, Td, Th } from '@/components/Table'
import { Button, EmptyState, Field, Flash, Input, MigrationNotice, PageHeader } from '@/components/ui'
import { MONTH_NAMES } from '@/lib/utils'
import { guard } from '@/lib/guard'
// eslint-disable-next-line @typescript-eslint/no-var-requires
const pr = require('@/lib/payroll-store')

export const metadata: Metadata = { title: 'Payroll' }
export const dynamic = 'force-dynamic'

type R = { id: string; year: number; month: number; status: string; createdBy: string; finalizedBy: string; finalizedAt: string | null }
const pad = (n: number) => String(n).padStart(2, '0')

export default async function PayrollPage({ searchParams }: { searchParams: { error?: string; saved?: string } }) {
  await guard()
  if (!(await pr.ready())) return <><PageHeader title="Payroll" /><MigrationNotice file="003_payroll.sql" /></>
  const [runs, s]: [R[], { exchangeRate: number | null }] = await Promise.all([pr.runs.list(), pr.settings.get()])
  const items: { label: string; done: boolean }[] = pr.readiness(s)
  const missing = items.filter(i => !i.done)
  const now = new Date()
  const thisMonth = `${now.getFullYear()}-${pad(now.getMonth() + 1)}`

  return (
    <>
      <PageHeader title="Payroll" note="Each month is generated from attendance, approved overtime, monthly items and pay setup. Review it, then finalize to lock it." />
      <Flash error={searchParams.error} saved={searchParams.saved} />

      {missing.length > 0 && (
        <p className="mb-5 max-w-[760px] rounded border border-late/35 bg-late-wash px-3.5 py-2.5 text-[14px] text-late">
          {missing.length} payroll setting{missing.length === 1 ? ' is' : 's are'} still empty, so a month cannot be finalized yet. <Link href="/settings/payroll" className="font-medium underline">Open Payroll settings</Link>.
        </p>
      )}

      <form method="get" action="/payroll/open" className="mb-6 flex flex-wrap items-end gap-3">
        <Field label="Open a month"><Input type="month" name="period" defaultValue={thisMonth} required className="w-[190px]" /></Field>
        <Button type="submit" variant="primary">Open</Button>
      </form>

      <TableWrap>
        <Table wide={false}>
          <thead><tr><Th>Month</Th><Th>Status</Th><Th>Generated by</Th><Th>Finalized</Th></tr></thead>
          <tbody>
            {runs.length === 0 && <tr><td colSpan={4}><EmptyState title="No payroll yet">Set up salaries under Pay setup, fill in Payroll settings, then open a month above and generate it.</EmptyState></td></tr>}
            {runs.map(r => (
              <tr key={r.id}>
                <Td className="font-medium"><Link href={`/payroll/${r.year}-${pad(r.month)}`} className="text-brand-deep underline decoration-line-strong hover:decoration-brand">{MONTH_NAMES[r.month - 1]} {r.year}</Link></Td>
                <Td>{r.status === 'finalized' ? <span className="inline-flex items-center gap-1.5 rounded-sm bg-present-wash px-2 py-0.5 text-[12px] font-medium text-present"><span className="h-1.5 w-1.5 rounded-full bg-current" aria-hidden />Finalized</span> : <span className="inline-flex items-center gap-1.5 rounded-sm bg-late-wash px-2 py-0.5 text-[12px] font-medium text-late"><span className="h-1.5 w-1.5 rounded-full bg-current" aria-hidden />Draft</span>}</Td>
                <Td className="text-ink-soft">{r.createdBy}</Td>
                <Td className="num text-ink-soft">{r.finalizedAt ? `${r.finalizedAt.slice(0, 10)}${r.finalizedBy ? ' by ' + r.finalizedBy : ''}` : ''}</Td>
              </tr>
            ))}
          </tbody>
        </Table>
      </TableWrap>
    </>
  )
}
